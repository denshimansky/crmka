/**
 * Разбор адреса MAX (web.max.ru) — какой чат открыт.
 *
 * У MAX нет хэша: это SvelteKit, и чат живёт прямо в пути. Живая проверка
 * 31.08.2026 (docs/messenger-extension.md §8, Шаг 1) дала ровно три формы:
 *
 *   • личный чат   — `web.max.ru/437719203`      (один ПОЛОЖИТЕЛЬНЫЙ сегмент);
 *   • групповой    — `web.max.ru/-78377804395205` (один ОТРИЦАТЕЛЬНЫЙ сегмент);
 *   • список чатов — `web.max.ru/`               (пустой путь).
 *
 * Знак и есть признак группы — ровно как в Telegram. Предположение спайка о
 * форме `/c/<chatId>/<messageId>` у групп живой проверкой НЕ подтвердилось: эта
 * форма, судя по всему, относится к ссылке на сообщение в канале.
 *
 * ПОЧЕМУ ЗДЕСЬ ПРАВИЛО СТРОЖЕ, ЧЕМ НА СЕРВЕРЕ. Серверный normalizeChatId
 * («lib/ext/chat-identity.ts») пропускает служебные префиксы `/c/`, `/u/` и
 * прочие: он разбирает ЛЮБУЮ строку, пришедшую от любой сборки расширения, в том
 * числе старой, и обязан хотя бы не склеивать разные чаты в один ключ. Адаптер же
 * видит ЖИВОЙ адрес открытой вкладки, и здесь неизвестная форма пути — это
 * сигнал «мы не понимаем, что открыто», а не повод угадывать. Цена ошибки
 * несимметрична: не показать карточку — досадно и обратимо, показать чужую и
 * залить в неё переписку — необратимо.
 *
 * Функция чистая: DOM не трогает, зовётся с `location.pathname` и покрыта
 * тестами (src/__tests__/max-path.test.js).
 */

/**
 * @typedef {object} MaxLocation
 * @property {"chat"|"group"|"chat-list"|"other"} kind Что открыто.
 *   chat — личный диалог (его и обслуживаем);
 *   group — групповой чат: панель его НЕ обслуживает (см. ниже);
 *   chat-list — список чатов, диалог не выбран;
 *   other — форма адреса, которую мы не понимаем (профиль, настройки, ссылка на
 *   сообщение канала). Ведём себя так же, как при списке чатов.
 * @property {string|null} chatId Идентификатор чата как есть, СТРОКОЙ.
 *   Числом его не делаем никогда: id MAX — длинное число, и Number() у него
 *   молча съест младшие разряды за пределами 2^53.
 */

/** Один сегмент пути, только цифры. Ноль — не чат. */
const POSITIVE = /^[1-9]\d*$/
/** Тот же сегмент со знаком минус — групповой чат. */
const NEGATIVE = /^-[1-9]\d*$/

/**
 * Адрес MAX → что открыто.
 *
 * @param {string|null|undefined} pathname Обычно `location.pathname`. Query и
 *   хэш отрезаем сами: вызвать могут и с полным адресом.
 * @returns {MaxLocation}
 */
export function parseMaxPath(pathname) {
  const raw = String(pathname ?? "")
  const path = raw.split(/[?#]/)[0] ?? ""
  const segments = path.split("/").filter((segment) => segment.trim().length > 0)

  if (segments.length === 0) return { kind: "chat-list", chatId: null }
  // Ровно ОДИН сегмент: две другие формы адреса у чата не встречаются, а
  // угадывать чат в многосегментном пути мы отказываемся сознательно.
  if (segments.length !== 1) return { kind: "other", chatId: null }

  const segment = segments[0].trim()
  if (POSITIVE.test(segment)) return { kind: "chat", chatId: segment }
  // Групповой чат отдаём вместе с id: панель показывает отдельную причину
  // («это групповой чат»), а не общее «откройте диалог». Молчать здесь плохо —
  // человек не поймёт, почему панель пуста именно тут.
  if (NEGATIVE.test(segment)) return { kind: "group", chatId: segment }
  return { kind: "other", chatId: null }
}

/**
 * Обслуживает ли панель то, что открыто.
 *
 * Групповые чаты — НЕТ, и это решение спеки (docs/messenger-extension.md §8,
 * Шаг 2): привязка группы к клиенту не рабочий сценарий, а цена ошибки
 * необратима — вся групповая переписка чужих родителей уедет в карточку одного
 * человека, и уникальный ключ дедупа не даст её оттуда убрать.
 *
 * @param {MaxLocation} location
 * @returns {boolean}
 */
export function isServiceableMaxChat(location) {
  return location.kind === "chat"
}
