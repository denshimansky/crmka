/**
 * Открытый чат глазами адаптера мессенджера.
 * @typedef {object} ChatContext
 * @property {Channel} channel
 * @property {string} chatId    Идентификатор собеседника из адресной строки
 *   (@username или числовой id). НЕ канон: в Telegram он зависит от того, есть ли
 *   у человека ник, и меняется вместе с ником.
 * @property {string[]} [altIds] Все идентификаторы этого же чата, увиденные в
 *   ОДИН момент в ОДНОМ открытом диалоге: значение из хэша плюс числовой peer id
 *   из разметки. Канон из них выбирает сервер — правило разное по каналам.
 * @property {string|null} [peerSource] Откуда взялся канон либо почему его нет.
 *   Только для диагностики в панели: поломка селекторов иначе молчалива.
 * @property {string} [localKey] Локальный ключ «тот же диалог или уже другой».
 *   НА СЕРВЕР НЕ УХОДИТ. Нужен там, где chatId пуст: в WhatsApp идентификатора
 *   чата в разметке нет вовсе, и различать открытые диалоги внутри расширения
 *   приходится по заголовку. Идентификатором заголовок быть не может (два тёзки
 *   дали бы одну карточку), а для локального сравнения годится — и цена промаха
 *   тут мала: сервер отдельно сверяет, какому клиенту принадлежат сообщения.
 * @property {string[]} [messageIds] Идентификаторы видимых сообщений — примета
 *   чата для каналов без собственного идентификатора. По ним сервер узнаёт
 *   диалог: сообщение принадлежит ровно одному чату, и такая примета переживает
 *   и переименование контакта, и совпадение имён.
 * @property {string|null} title Отображаемое имя собеседника, если удалось прочитать.
 * @property {string|null} phone Телефон, если канал его отдаёт (Telegram — почти никогда).
 * @property {"group"|"no-id"|null} [unsupported] Чат открыт, но панель его
 *   не обслуживает. Прятать такой чат нельзя: панель обязана объяснить, почему
 *   карточки здесь нет, иначе человек прочитает молчание как поломку.
 *
 *   «group» — за чатом стоит не один человек: групповой чат MAX (отрицательный
 *   id), а в WhatsApp ещё и рассылки, статусы и каналы. Привязка такого чата к
 *   клиенту не рабочий сценарий, а цена ошибки необратима — вся переписка чужих
 *   родителей уедет в карточку одного человека.
 *
 *   «no-id» — только WhatsApp: собеседника нечем опознать. Идентификатора чата
 *   там нет в разметке ВООБЩЕ (проверено живым прогоном: ни JID, ни номера — ни
 *   в одном атрибуте), а единственная опора, телефон из заголовка, видна лишь у
 *   контактов, не сохранённых в телефонной книге. Имя за идентификатор не
 *   берём: два тёзки схлопнулись бы в одну карточку необратимо. Это не поломка
 *   и не «чат не выбран», а третье состояние, и назвать его надо своими словами.
 */

