/**
 * Сообщение MAX: что считать перепиской и под каким ключом её хранить.
 *
 * ДВЕ ЗАДАЧИ, ОБЕ ИЗ-ЗА ОСОБЕННОСТЕЙ MAX (docs/messenger-extension.md §8, Шаг 1).
 *
 * 1. СЛУЖЕБНЫЕ СТРОКИ. Звонки MAX рисует в общей ленте обычным текстом —
 *    «Отменённый вызов Видео», «Пропущенный вызов Аудио». Они не пустые, поэтому
 *    наивный сбор утащил бы их в карточку клиента как реплики родителя. Стикеры
 *    и фото такой опасности не несут: после вычистки `.meta` их текст пустеет.
 *
 * 2. КЛЮЧ ДЕДУПА. Идентификатора сообщения в разметке MAX нет ВООБЩЕ — проверено
 *    пятью прогонами probe, у узла только `role` и `class`. Значит ключ надо
 *    синтезировать из того, что видно: чат, направление, время, текст. Отсюда
 *    два известных и принятых дефекта: правка сообщения даст в карточке вторую
 *    строку, а два одинаковых коротких сообщения в одну минуту схлопнутся в одну.
 *
 * Чистые функции, без DOM — покрыты тестами (src/__tests__/max-message.test.js).
 */

/**
 * Версия схемы ключа. Обязательна: ключ синтетический, и любое изменение правил
 * его сборки (добавили секунды, сменили нормализацию текста) породит вторую
 * строку на то же сообщение. Версия в ключе делает разовую чистку возможной
 * ОДНИМ запросом — `external_id LIKE '%:m1-%'` — вместо разбора всей ленты.
 *
 * Меняя правила сборки — поднимайте версию, а не правьте старую тихо.
 */
export const MAX_KEY_VERSION = "m1"

/**
 * Строка звонка целиком: необязательное определение («Пропущенный»,
 * «Отменённый», …), слово «вызов»/«звонок», необязательный вид («Аудио»/«Видео»)
 * и необязательная длительность («1:05»). Вид может стоять и перед словом —
 * «Видеовызов» MAX тоже пишет.
 */
const CALL_LINE =
  /^(?:(?:пропущенн|отмен[её]нн|исходящ|входящ|заверш[её]нн|отклон[её]нн|несостоявш\S*|неудачн)\S*\s+)?(?:аудио|видео)?[ -]?(?:вызов|звонок)(?:\s+(?:аудио|видео))?(?:\s+\d{1,2}:\d{2}(?::\d{2})?)?$/i

/**
 * Служебная строка ленты: звонок или системное уведомление.
 *
 * Сверяем ЦЕЛИКОМ, а не по вхождению слова. Родитель вполне может написать
 * «пропущенный вызов, перезвоните пожалуйста» — и такое сообщение обязано
 * попасть в карточку. А вот строка, состоящая ровно из «Пропущенный вызов Аудио»,
 * человеческим сообщением не бывает.
 *
 * ЭТО ВРЕМЕННАЯ МЕРА, И ОНА СЛОВАРНАЯ. Структурного признака служебной строки мы
 * пока не знаем — в probe v5 (docs §8.1) это первый вопрос. Любая новая
 * формулировка MAX просочится в карточку клиента, пока признак не найден.
 * Поэтому: словарь узкий, проверка полная, ложное срабатывание дороже пропуска.
 *
 * @param {string|null|undefined} text Текст сообщения ПОСЛЕ вычистки `.meta`.
 * @returns {boolean}
 */
export function isServiceLine(text) {
  const value = String(text ?? "")
    .replace(/\s+/g, " ")
    .trim()
  if (!value) return false
  return CALL_LINE.test(value)
}

/**
 * Нормализация текста ДЛЯ КЛЮЧА (не для хранения).
 *
 * Разметка мессенджера перерисовывается, и один и тот же текст между двумя
 * чтениями легко приходит с разными пробелами и переносами. Ключ обязан это
 * переживать: иначе то же сообщение получит второй ключ и ляжет в карточку
 * второй строкой. В CRM при этом уезжает ОРИГИНАЛЬНЫЙ текст с переносами —
 * нормализуем только то, что идёт в хеш.
 *
 * @param {string|null|undefined} text
 * @returns {string}
 */
function normalizeForKey(text) {
  return String(text ?? "")
    .replace(/\s+/g, " ")
    .trim()
}

/**
 * FNV-1a, 32 бита. Своя реализация, потому что синхронного хеша в браузере нет
 * (SubtleCrypto асинхронный), а ключ нужен внутри разбора DOM.
 *
 * @param {string} value
 * @param {number} seed
 * @returns {number}
 */
function hash32(value, seed) {
  let h = seed >>> 0
  for (let i = 0; i < value.length; i++) {
    h ^= value.charCodeAt(i)
    // Math.imul — умножение на простое FNV с переполнением как в 32-битной
    // арифметике; обычное «*» здесь потеряло бы старшие разряды в double.
    h = Math.imul(h, 16777619) >>> 0
  }
  return h >>> 0
}

/**
 * Два независимых хеша + длина строки. 32 бита дали бы коллизию примерно на
 * 77 тысячах сообщений (парадокс дней рождения), а коллизия здесь означает
 * ПОТЕРЮ сообщения: сервер сочтёт его дублем и не запишет. 64 бита с длиной
 * сверху делают этот риск пренебрежимым.
 *
 * @param {string[]} parts Поля ключа. Склеиваем через «\u0000»: в тексте
 *   сообщения нулевого байта быть не может, поэтому границу полей не подделать.
 * @returns {string}
 */
function digest(parts) {
  const payload = parts.join("\u0000")
  const a = hash32(payload, 2166136261)
  const b = hash32(payload, 0x9e3779b9)
  return (
    a.toString(16).padStart(8, "0") +
    b.toString(16).padStart(8, "0") +
    payload.length.toString(36)
  )
}

/**
 * Ключ сообщения MAX для дедупликации в CRM.
 *
 * Сервер склеит его с каноническим chatId («<chatId>:<этот ключ>»,
 * buildMessageExternalId), но chatId входит и сюда — чтобы ключ не зависел от
 * серверного правила склейки: поменяется оно — сообщения разных чатов всё равно
 * не столкнутся.
 *
 * БЕЗ ВРЕМЕНИ КЛЮЧА НЕТ. Это не мелочь, а гард: время — единственная часть
 * ключа, которая отличает два одинаковых сообщения в разные дни. Без него ключ
 * стал бы недетерминированным относительно момента чтения, и карточка получала
 * бы копию переписки при каждом открытии чата. Потеря сообщения обратима (оно
 * зальётся, когда время разберётся), дубль — нет.
 *
 * @param {object} input
 * @param {string} input.chatId Идентификатор чата из адреса.
 * @param {"incoming"|"outgoing"} input.direction
 * @param {string|null|undefined} input.sentAt ISO-время (common/max-time.js).
 * @param {string|null|undefined} input.text Текст сообщения.
 * @returns {string|null} null — данных не хватает, сообщение заливать нельзя.
 */
export function buildMaxMessageId(input) {
  const chatId = String(input?.chatId ?? "").trim()
  const direction = input?.direction === "outgoing" ? "outgoing" : "incoming"
  const sentAt = String(input?.sentAt ?? "").trim()
  const text = normalizeForKey(input?.text)
  if (!chatId || !sentAt || !text) return null
  return `${MAX_KEY_VERSION}-${digest([chatId, direction, sentAt, text])}`
}

/**
 * Отпечаток «самого свежего сообщения» — по нему адаптер понимает, что в чате
 * что-то появилось, и будит панель.
 *
 * От ключа отличается тем, что время НЕ обязательно: сигнал активности ничего не
 * записывает, а молчать из-за неразобранной капсулы было бы обидно. Заодно это
 * страховка на случай, если разбор времени сломается: панель продолжит
 * обновляться, просто перестанет заливать.
 *
 * @param {object} input
 * @param {"incoming"|"outgoing"} input.direction
 * @param {string|null|undefined} [input.clock] Часы из `.meta` («16:15»).
 * @param {string|null|undefined} input.text
 * @returns {string|null}
 */
export function buildMaxActivityKey(input) {
  const text = normalizeForKey(input?.text)
  const clock = normalizeForKey(input?.clock)
  if (!text && !clock) return null
  const direction = input?.direction === "outgoing" ? "outgoing" : "incoming"
  return digest([direction, clock, text])
}
