def numbered(items):
    """Возвращает строку с нумерованными пунктами через перенос строки."""
    return "\n".join(f"{i+1}. {x}" for i, x in enumerate(items))


def main():
    wb = Workbook()
    ws = wb.active
    ws.title = "Отчёты"

    thin = Side(style="thin", color="D1D5DB")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)

    row_idx = 1
    for module in MODULES:
        for report in module["reports"]:
            whats = [d[0] for d in report["data"]]
            froms = [d[1] for d in report["data"]]

            ws.cell(row=row_idx, column=1, value=module["title"])
            ws.cell(row=row_idx, column=2, value=report["id"])
            ws.cell(row=row_idx, column=3, value=report["name"])
            ws.cell(row=row_idx, column=4, value=numbered(whats))
            ws.cell(row=row_idx, column=5, value=numbered(froms))
            ws.cell(row=row_idx, column=6, value=report["formula"])
            ws.cell(row=row_idx, column=7, value=STATUS_LABEL[report["status"]])
            ws.cell(row=row_idx, column=8, value=report["gap"])

            # Стили
            for col in range(1, 9):
                cell = ws.cell(row=row_idx, column=col)
                cell.alignment = Alignment(
                    wrap_text=True,
                    vertical="top",
                    horizontal="left",
                )
                cell.font = Font(name="Arial", size=10)
                cell.border = border

            # Подсветка статуса
            ws.cell(row=row_idx, column=7).fill = STATUS_FILL[report["status"]]
            ws.cell(row=row_idx, column=7).font = Font(name="Arial", size=10, bold=True)

            # Жирная категория и ID
            ws.cell(row=row_idx, column=1).font = Font(name="Arial", size=10, bold=True)
            ws.cell(row=row_idx, column=2).font = Font(name="Arial", size=10, bold=True)

            row_idx += 1

    # Ширина колонок
    widths = {
        "A": 22,  # Категория
        "B": 14,  # ID
        "C": 36,  # Отчёт
        "D": 52,  # Требуемые данные
        "E": 60,  # Откуда берём
        "F": 60,  # Формула
        "G": 14,  # Статус
        "H": 50,  # Чего не хватает
    }
    for col, w in widths.items():
        ws.column_dimensions[col].width = w

    # Высота строк — авто по содержимому (openpyxl не умеет авто, ставим минимум)
    for r in range(1, row_idx):
        ws.row_dimensions[r].height = None  # авто

    output_path = "reps-report.xlsx"
    wb.save(output_path)

    # Статистика
    total = sum(len(m["reports"]) for m in MODULES)
    print(f"Saved {output_path}")
    print(f"Total rows: {total}")
    for m in MODULES:
        print(f"  {m['title']}: {len(m['reports'])}")


if __name__ == "__main__":
    main()
