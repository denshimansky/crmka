-- «Не был» больше никогда не разрешает отчисление (решение 22.08.2026).
--
-- Статус промежуточный: ребёнок не пришёл, а причина (Уваж. пропуск / Прогул /
-- отработка) ещё не выбрана — деньги и ЗП по нему не двинуты. Отчисление с таким
-- статусом навсегда замораживало занятие в подвешенном состоянии: переставить
-- статус на отчисленном абонементе уже некому, а в реестре «Пропуски» строка
-- висела вечно. Теперь флаг залочен, как у «Назначена отработка»: снять галку в
-- матрице нельзя ни в UI, ни через API.
--
-- Данные приводим к новому правилу в обе стороны:
--  1) общая (системная, tenant_id IS NULL) строка типа — дефолт для новых центров;
--  2) пер-организационные оверрайды, где центр выставил «разрешено» вручную.
-- На 22.08.2026 таких оверрайдов было три: два уже стояли false (ДЦ Умный Я,
-- Школа студия Class), один true (Детский центр «Умные дети»).
UPDATE "attendance_types"
   SET "allow_subscription_withdrawal" = false
 WHERE "code" = 'no_show';

UPDATE "attendance_type_withdrawal_overrides"
   SET "allow_subscription_withdrawal" = false
 WHERE "attendance_type_id" IN (SELECT "id" FROM "attendance_types" WHERE "code" = 'no_show');
