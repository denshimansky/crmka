-- Остальные отбираются под конкретный вопрос (lib/ai-faq-select.ts), поэтому
-- общие правила ответов должны быть помечены как ядро — иначе на непокрытом
-- вопросе модель останется без них.
-- Аддитивно: колонка с DEFAULT false, существующие строки не трогаются.
-- Индекс не заводим намеренно: в таблице десятки строк, выборка идёт полным
-- сканом дешевле, а лишний индекс пришлось бы держать вне schema.prisma.
ALTER TABLE "ai_faq" ADD COLUMN IF NOT EXISTS "is_core" BOOLEAN NOT NULL DEFAULT false;
