-- sent_at становится единым «временем события» коммуникации.
--
-- Зачем: ленты (карточка клиента, таймлайн, панель расширения) сортируются по
-- одному полю. Если у части строк sent_at пуст, приходится городить
-- COALESCE(sent_at, created_at) в каждом запросе, а Prisma так не умеет —
-- сортировка по двум полям поставила бы записи без sent_at неверно (NULL-хвост).
--
-- Решение аддитивное: дефолт now() для новых строк (код создания коммуникаций
-- править не нужно — БД проставит сама) + разовый бэкфилл существующих.
-- Расширение при заливке передаёт настоящее время сообщения и перекрывает дефолт.

ALTER TABLE "communications" ALTER COLUMN "sent_at" SET DEFAULT CURRENT_TIMESTAMP;

UPDATE "communications" SET "sent_at" = "created_at" WHERE "sent_at" IS NULL;
