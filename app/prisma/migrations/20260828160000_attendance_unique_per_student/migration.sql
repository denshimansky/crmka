-- Инвариант: один ребёнок на одном занятии = ОДНА отметка.
--
-- До 28.08.2026 единственным ограничением было UNIQUE(tenant_id, lesson_id,
-- subscription_id), а clientId/wardId в него не входят. Поэтому смена
-- резолвнутого абонемента (пакет A исчерпан, пакет B выписан задним числом с
-- пересечением периода → FIFO выдал B) давала ВТОРУЮ отметку на том же занятии:
-- одно занятие списывалось с двух абонементов — перерасход первого пакета
-- (фантомный долг), сгоревшее занятие второго, задвоенные ЗП и выручка.
-- Кейс: Тарасова Марина, занятие 26.08.2026.
--
-- Первопричина исправлена в API (POST/PUT /api/lessons/[id]/attendance
-- переиспользуют строку ребёнка), этот индекс — страховка на уровне БД, чтобы
-- инвариант нельзя было сломать новым путём записи.
--
-- NULLS NOT DISTINCT (PG15+, на проде 17.9) обязателен: у 236 отметок ward_id
-- пустой (клиент без подопечных), а при обычной семантике NULL такие строки
-- ограничением не покрывались бы вовсе.
--
-- Частичный: пробное (is_trial) и отработка (is_makeup) — ОТДЕЛЬНЫЕ визиты
-- ребёнка на том же занятии со своей семантикой и своими ключами, они законно
-- сосуществуют с обычной отметкой.
--
-- Проверено на проде перед выпуском: нарушений предиката 0.
CREATE UNIQUE INDEX "attendances_tenant_lesson_client_ward_key"
  ON "attendances"("tenant_id", "lesson_id", "client_id", "ward_id")
  NULLS NOT DISTINCT
  WHERE NOT "is_trial" AND NOT "is_makeup";
