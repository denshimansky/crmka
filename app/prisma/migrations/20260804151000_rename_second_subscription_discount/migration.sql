-- Переименование системной автоскидки «Скидка за второй абонемент» →
-- «Скидка за второй и следующие» (соответствует реальному поведению: скидку
-- несут все абонементы месяца, кроме самого дорогого, — а не только «второй»).
-- Имя системного шаблона в UI не редактируется, поэтому переименовываем все
-- строки этого системного ключа у всех тенантов.
UPDATE "discount_templates"
SET "name" = 'Скидка за второй и следующие'
WHERE "system_key" = 'second_subscription';
