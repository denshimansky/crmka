/** Что подставляем, когда данных нет. Видно глазами до отправки. */
export const EMPTY_VALUE = "—"

/** Ключ плейсхолдера без регистра, «ё» и пробелов по краям. */
function normalizeKey(key: string): string {
  return key.trim().toLowerCase().replace(/ё/g, "е")
}

/**
 * Подставить значения в текст шаблона.
 *
 * Незнакомый ключ оставляем как есть: это опечатка в шаблоне, и молча съесть
 * кусок текста хуже, чем показать «{ребенк}» перед отправкой — человек всё
 * равно вычитывает сообщение, прежде чем нажать «отправить».
 *
 * «ё» и «е» считаем одной буквой: в каталоге у нас «{ребёнок}», а наберут
 * почти наверняка «{ребенок}».
 */
export function expandTemplate(body: string, values: Record<string, string>): string {
  const normalized = new Map(
    Object.entries(values).map(([key, value]) => [normalizeKey(key), value]),
  )
  return body.replace(/\{([^{}]{1,64})\}/g, (whole, rawKey: string) => {
    const value = normalized.get(normalizeKey(rawKey))
    return value === undefined ? whole : value
  })
}
