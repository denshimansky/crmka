/**
 * Удалённый конфиг селекторов для расширения (docs/messenger-extension.md §3, Шаг 4).
 *
 * ЗАЧЕМ. Адаптеры цепляются за разметку чужих сайтов, и она меняется без
 * предупреждения. У MAX это не «когда-нибудь», а расписание: Svelte хеширует
 * классы на каждой сборке, и авторскую часть класса тоже могут переименовать.
 * Если селекторы зашиты в код расширения, починка означает публикацию в Chrome
 * Web Store — а это дни ревью, в течение которых канал не работает у всех.
 *
 * MV3 запрещает удалённый КОД, но разрешает удалённые ДАННЫЕ. Селекторы — данные.
 * Поэтому расширение спрашивает их у своей же CRM и держит в кэше, а починка
 * сломавшегося канала становится правкой этого файла и деплоем (минуты).
 *
 * ЗДЕСЬ ЛЕЖАТ ТОЛЬКО ПЕРЕОПРЕДЕЛЕНИЯ, А НЕ ПОЛНЫЙ НАБОР. Это важно: полный набор
 * на сервере неизбежно разошёлся бы со встроенным в расширение (там его правят
 * при разработке адаптера, здесь — при аварии), и однажды сервер молча вернул бы
 * канал к устаревшим селекторам. Пустой объект = «у нас всё в порядке, работайте
 * на встроенных».
 *
 * КАК ЧИНИТЬ КАНАЛ (порядок действий при аварии):
 *   1. открыть сломавшийся мессенджер, найти новый селектор (extension/tools/
 *      max-probe.js собирает разметку за один прогон);
 *   2. дописать его в CHANNEL_OVERRIDES ниже и поднять VERSION;
 *   3. запушить — расширение подхватит конфиг само (кэш живёт 6 часов, а панель
 *      обновляет его при каждом открытии, если кэш просрочен);
 *   4. потом починить встроенные значения в extension/src/content/<канал>.js и
 *      убрать переопределение отсюда — иначе оно останется навсегда.
 *
 * ИМЕНА КЛЮЧЕЙ — из адаптера канала (`DEFAULTS` в extension/src/content/max.js).
 * Неизвестный ключ расширение молча игнорирует: подсунуть им новое поведение
 * нельзя, а опечатка не ломает канал.
 */

/** Каналы, у которых есть адаптер с настраиваемыми селекторами. */
export type ConfigurableChannel = "max" | "telegram" | "whatsapp"

/** Значение селектора: строка либо список кандидатов (пробуем по порядку). */
export type SelectorValue = string | string[]

export interface SelectorConfig {
  /** Поднимать при каждой правке — по нему видно в диагностике, что приехало. */
  version: number
  updatedAt: string
  channels: Partial<Record<ConfigurableChannel, Record<string, SelectorValue>>>
}

/**
 * Дата последней правки переопределений. Руками, а не `new Date()`: иначе поле
 * менялось бы на каждый запрос и по нему нельзя было бы понять, что изменилось.
 */
const UPDATED_AT = "2026-08-31T00:00:00.000Z"

/** Версия набора. Поднимать вместе с любой правкой CHANNEL_OVERRIDES. */
const VERSION = 1

/**
 * Переопределения селекторов по каналам. В норме пусто — см. шапку.
 *
 * Пример аварийной правки (MAX переименовал пузырь):
 *   max: { bubble: '[class*="msgWrapper"]' }
 */
const CHANNEL_OVERRIDES: SelectorConfig["channels"] = {}

export function buildSelectorConfig(): SelectorConfig {
  return { version: VERSION, updatedAt: UPDATED_AT, channels: CHANNEL_OVERRIDES }
}
