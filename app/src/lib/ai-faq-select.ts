/**
 * Отбор записей базы знаний ассистента (`ai_faq`) под конкретный вопрос.
 *
 * Зачем. Раньше в промпт подмешивались ВСЕ записи разом, и вместе с FAQ из кода
 * статическая часть доросла до ~50k токенов. Проблема не только в цене (она
 * кэшируется): на «книге правил» такого размера модель хуже держит инструкции, а
 * дубли между записями дают ей выбор между двумя формулировками одного факта.
 *
 * Схема. Записи с `isCore` идут в промпт ВСЕГДА (общие правила ответов: «не
 * выдумывай кнопки», «не отправляй в техподдержку», термины). Остальные
 * отбираются по совпадению слов вопроса. Ядро обязательно: без него на вопросе,
 * который не попал ни в одну запись, модель снова начнёт выдумывать интерфейс.
 *
 * Совпадение грубое, по префиксу слова (см. stem): русская морфология иначе
 * разводит «абонемент/абонементы/абонементу» по разным токенам. Точность здесь
 * важнее полноты наоборот — лучше подмешать лишнюю запись, чем не подмешать
 * нужную, поэтому порог низкий, а лимит щедрый.
 */

/**
 * Служебные слова, которые не несут темы. НАМЕРЕННО короткий список: доменные
 * слова («абонемент», «клиент», «группа», «оплата») здесь НЕ стоп-слова — именно
 * по ним запись и находится. Не путать со STOPWORDS в ai-context.ts: там они
 * гасят ложные совпадения при поиске человека по имени, задача обратная.
 */
const STOPWORDS = new Set([
  "если", "иначе", "тогда", "потому", "значит", "итак", "потом", "далее", "чтобы",
  "этот", "этом", "этой", "этих", "тот", "там", "тут", "здесь", "куда", "откуда",
  "почему", "зачем", "когда", "какой", "какая", "какое", "какие", "который",
  "наш", "наша", "наше", "наши", "мой", "моя", "моё", "мои", "меня", "мне", "нам",
  "нас", "вас", "вам", "его", "него", "неё", "них", "имя",
  "быть", "было", "были", "будет", "будут", "есть", "стало", "стали",
  "надо", "нужно", "нужен", "нужна", "хочу", "хочет", "хотел", "хотела",
  "можно", "нельзя", "могу", "может", "мочь",
  "тоже", "также", "только", "ещё", "уже", "очень", "более", "менее",
  "сегодня", "вчера", "завтра", "сейчас", "теперь",
  "пожалуйста", "спасибо", "здравствуйте", "привет", "добрый", "день",
  "подскажите", "скажите", "помогите", "вопрос", "система", "программа",
])

/**
 * Грубая основа слова: первые 5 символов. Склеивает «абонемент/абонементы»,
 * «группа/группы/группе», «списать/списание» — этого достаточно, чтобы вопрос
 * человека попал в запись, написанную другими падежами. Слова короче 5 символов
 * берём целиком.
 */
export function stem(word: string): string {
  const w = word.toLowerCase().replace(/ё/g, "е")
  return w.length <= 5 ? w : w.slice(0, 5)
}

/** Основы значимых слов текста (дубли схлопнуты). */
export function stems(text: string): Set<string> {
  const out = new Set<string>()
  for (const raw of text.toLowerCase().match(/[a-zа-яё]{4,}/gi) || []) {
    const w = raw.toLowerCase()
    if (STOPWORDS.has(w)) continue
    out.add(stem(w))
  }
  return out
}

export interface FaqRow {
  question: string
  answer: string
  keywords?: string | null
  isCore?: boolean
}

/**
 * Вес совпадения по частям записи. Вопрос и ключевые слова — это тема записи,
 * попадание в них означает «человек спрашивает именно про это». Ответ длинный и
 * упоминает попутные термины, поэтому совпадение в нём стоит меньше и участвует
 * скорее как тай-брейк.
 */
const WEIGHT_QUESTION = 3
const WEIGHT_KEYWORDS = 3
const WEIGHT_ANSWER = 1

/**
 * Сколько отбираемых (не ядровых) записей подмешивать максимум.
 *
 * Проверено на 125 реальных вопросах из разбора 25–31.08.2026: нужная запись
 * попадает в подборку в 19 случаях из 20 уже при лимите 10 (худшая позиция — 10-я),
 * при 5 — только в 16. Берём 12: запас в две позиции на вопросы из двух слов
 * («унас нет кнопки списать»), где совпадений мало и ранжирование шаткое.
 */
export const DEFAULT_LIMIT = 12

export function scoreRow(row: FaqRow, queryStems: Set<string>): number {
  if (queryStems.size === 0) return 0
  const q = stems(row.question)
  const k = stems(row.keywords || "")
  const a = stems(row.answer)
  let score = 0
  for (const s of queryStems) {
    if (q.has(s)) score += WEIGHT_QUESTION
    if (k.has(s)) score += WEIGHT_KEYWORDS
    if (a.has(s)) score += WEIGHT_ANSWER
  }
  return score
}

export interface SelectResult<T extends FaqRow> {
  /** Записи-правила: в промпт идут всегда, в стабильном (кэшируемом) блоке. */
  core: T[]
  /** Отобранные под вопрос — идут в некэшируемую часть промпта. */
  matched: T[]
}

/**
 * Делит записи на ядро и отобранные под вопрос.
 *
 * Порядок внутри `matched` — по убыванию совпадения, при равенстве сохраняется
 * исходный порядок (он приходит из БД по sortOrder), чтобы выдача не «плавала»
 * между одинаковыми запросами.
 */
export function selectFaq<T extends FaqRow>(
  rows: T[],
  message: string,
  limit: number = DEFAULT_LIMIT,
): SelectResult<T> {
  const core = rows.filter((r) => r.isCore)
  const rest = rows.filter((r) => !r.isCore)

  const queryStems = stems(message)
  // Пустой или бессмысленный вопрос («?», «ок») — отбирать нечего, остаётся ядро.
  if (queryStems.size === 0) return { core, matched: [] }

  const scored = rest
    .map((row, index) => ({ row, index, score: scoreRow(row, queryStems) }))
    .filter((x) => x.score > 0)
    .sort((a, b) => (b.score - a.score) || (a.index - b.index))

  return { core, matched: scored.slice(0, limit).map((x) => x.row) }
}

/**
 * Текст блока для промпта. Пустой массив → "" (вызывающий не добавит пустую
 * секцию). Заголовок разный у ядра и выборки: у выборки нужно явно сказать
 * модели, что это НЕ полный список её знаний, иначе она склонна отвечать
 * «такого в системе нет» на всё, чего не оказалось в подмешанном куске.
 */
export function renderFaqBlock(rows: FaqRow[], kind: "core" | "matched"): string {
  if (rows.length === 0) return ""
  const header =
    kind === "core"
      ? "БАЗА ЗНАНИЙ — ОБЩИЕ ПРАВИЛА (действуют всегда, приоритет над остальными инструкциями):"
      : "БАЗА ЗНАНИЙ — УТОЧНЕНИЯ ПО ТЕМЕ ВОПРОСА (внесены вручную по разбору реальных вопросов, считай их достоверными; при конфликте с общими инструкциями приоритет у них). Это ПОДБОРКА под текущий вопрос, а не весь объём знаний о системе: если нужного факта здесь нет — опирайся на карту навигации и честно скажи, что не уверен, но не выдумывай кнопки и разделы:"
  const blocks = rows.map((f) => `Вопрос: «${f.question}»\nОтвет: ${f.answer}`)
  return `${header}\n\n${blocks.join("\n\n")}`
}
