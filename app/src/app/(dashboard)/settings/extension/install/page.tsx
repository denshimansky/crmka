import { ArrowLeft } from "lucide-react"
import Link from "next/link"
import { BackButton } from "@/components/back-button"
import { PageHelp } from "@/components/page-help"

/**
 * «Настройки → Расширение → Как установить» (docs/messenger-extension.md §7).
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ СТРАНИЦА. Справка CRM уже обещает сотруднику ссылку на
 * установку («Установите расширение в браузер по ссылке, которую даёт CRMka» —
 * page-help-content.ts), а ссылки не было. Это один из шести блокеров раздачи
 * расширения партнёрам.
 *
 * ПОЧЕМУ ЗДЕСЬ ДВА СЦЕНАРИЯ. Пока расширение не опубликовано в Chrome Web Store,
 * поставить его можно только распакованной папкой — и делать вид, что это
 * «временная мелочь», нельзя: человеку нужно знать, что он делает и почему у
 * него включается режим разработчика. Когда публикация состоится, достаточно
 * заполнить STORE_URL, и страница сама переключится на сценарий в одну кнопку,
 * а инструкция для разработчика уедет под спойлер.
 *
 * Прав отдельных не заводим: /settings/* уже требует settings.view.
 */

/**
 * Ссылка на расширение в Chrome Web Store.
 *
 * ЗАПОЛНИТЬ ПОСЛЕ ПУБЛИКАЦИИ (режим unlisted — расширения не будет ни в
 * каталоге, ни в поиске, только по прямой ссылке). Пустая строка означает
 * «ещё не опубликовано», и страница показывает сценарий с распакованной папкой.
 */
const STORE_URL = ""

/** Где сотрудник берёт архив, пока публикации нет. Собирается `tools/pack.mjs`. */
const ZIP_HINT = "crmka-extension-<версия>.zip"

export default function ExtensionInstallPage() {
  const published = STORE_URL.length > 0

  return (
    <div className="space-y-6">
      <div className="flex items-center gap-3">
        <BackButton
          fallbackHref="/settings/extension"
          className="text-muted-foreground hover:text-foreground"
        >
          <ArrowLeft className="size-5" />
        </BackButton>
        <div>
          <div className="flex items-center gap-2">
            <h1 className="text-2xl font-bold">Как установить расширение</h1>
            <PageHelp pageKey="settings/extension/install" />
          </div>
          <p className="text-sm text-muted-foreground">
            Панель CRM рядом с чатом в веб-мессенджере
          </p>
        </div>
      </div>

      <section className="rounded-lg border p-4 text-sm leading-relaxed space-y-2">
        <h2 className="font-semibold">Что это</h2>
        <p>
          Расширение показывает карточку клиента рядом с открытым чатом в веб-версии
          мессенджера: дети, занятия, абонементы, баланс и переписка по всем каналам. Оттуда
          же можно поставить задачу, оставить комментарий и вставить справку в поле ввода.
        </p>
        <p>Работает в четырёх мессенджерах — в их веб-версиях:</p>
        <ul className="list-disc pl-5 space-y-1">
          <li>
            <strong>ВКонтакте</strong> — сообщения сообщества (<code>vk.ru/gim…</code>) и
            личные сообщения
          </li>
          <li>
            <strong>Телеграм</strong> — <code>web.telegram.org</code>
          </li>
          <li>
            <strong>MAX</strong> — <code>web.max.ru</code>
          </li>
          <li>
            <strong>WhatsApp</strong> — <code>web.whatsapp.com</code> (в России открывается
            только через VPN)
          </li>
        </ul>
        <p className="text-muted-foreground">
          Браузер — Google Chrome, Яндекс Браузер или Microsoft Edge на компьютере. Мобильные
          версии и настольные приложения мессенджеров не поддерживаются: расширение живёт в
          браузере.
        </p>
      </section>

      {published ? (
        <Step num="1" title="Установить расширение">
          <p>
            Откройте страницу расширения и нажмите «Установить»:{" "}
            <a href={STORE_URL} target="_blank" rel="noreferrer" className="underline">
              {STORE_URL}
            </a>
          </p>
          <p className="text-muted-foreground">
            Расширения нет в каталоге магазина — оно ставится только по этой ссылке.
          </p>
        </Step>
      ) : (
        <Step num="1" title="Установить расширение (пока вручную)">
          <p>
            Расширение ещё не опубликовано в магазине, поэтому ставится папкой. Это
            безопасно, но браузер попросит включить режим разработчика — так он поступает с
            любым расширением не из магазина.
          </p>
          <ol className="list-decimal pl-5 space-y-1">
            <li>
              Получите у нас архив <code>{ZIP_HINT}</code> и распакуйте его в постоянную
              папку — например <code>C:\CRMka\extension</code>. <strong>Папку не удалять и
              не переносить:</strong> браузер грузит расширение прямо из неё, и после
              переезда оно перестанет работать. Папка «Загрузки» для этого не годится —
              оттуда файлы часто чистят.
            </li>
            <li>
              Внутри папки должен лежать файл <code>manifest.json</code>. Если он оказался
              ещё в одной вложенной папке — выбирать на шаге 4 надо именно её.
            </li>
            <li>
              Откройте в браузере адрес <code>chrome://extensions</code> (в Яндекс Браузере —{" "}
              <code>browser://extensions</code>, в Edge — <code>edge://extensions</code>).
            </li>
            <li>Включите переключатель «Режим разработчика» в правом верхнем углу.</li>
            <li>Нажмите «Загрузить распакованное расширение» и выберите папку из шага 1.</li>
            <li>
              В панели браузера появится иконка расширения — закрепите её, нажав значок
              пазла рядом с адресной строкой и булавку напротив «Умной CRM».
            </li>
          </ol>
          <p className="text-muted-foreground">
            При каждом запуске браузер будет показывать предупреждение «Отключите
            расширения, работающие в режиме разработчика». Его можно закрывать — так браузер
            ведёт себя с любым расширением не из магазина. После публикации в магазине
            установка станет установкой в одну кнопку, предупреждение исчезнет, а обновления
            будут приходить сами.
          </p>
        </Step>
      )}

      <Step num="2" title="Выпустить токен — по одному на рабочее место">
        <p>
          Токен связывает браузер с CRM. Выпускается на странице{" "}
          <Link href="/settings/extension" className="underline">
            Расширение для мессенджеров
          </Link>
          , и при выпуске у него спрашивают название рабочего места — «ПК Филиал 1»,
          «Ноутбук администратора».
        </p>
        <p>
          <strong>Название важно:</strong> именно им подписываются сообщения и заметки,
          которые панель пишет в карточку клиента. По нему потом видно, с какого компьютера
          вели общение с родителем. Поэтому на каждый компьютер — свой токен со своим
          названием, а не один на всех.
        </p>
        <p className="text-muted-foreground">
          Токен показывается один раз — скопируйте его сразу. Потерянный не восстанавливают,
          а выпускают заново; старый при этом стоит отозвать. Права и филиалы у панели ровно
          те же, что у сотрудника, выпустившего токен: лишнего она не покажет.
        </p>
      </Step>

      <Step num="3" title="Подключить расширение к CRM">
        <ol className="list-decimal pl-5 space-y-1">
          <li>Откройте веб-версию мессенджера и нажмите иконку расширения — справа
            откроется панель.</li>
          <li>При первом запуске панель покажет, какие данные она собирает. Прочитайте и
            нажмите «Понятно, продолжить».</li>
          <li>Вставьте адрес вашей CRM и токен, нажмите «Сохранить».</li>
        </ol>
      </Step>

      <Step num="4" title="Включить запись переписки — если центр этого хочет">
        <p>
          Отдельный переключатель «Записывать переписку в историю клиента». По умолчанию он
          <strong> выключен</strong>: сохранение переписки — это обработка персональных
          данных, и включать её нужно осознанно.
        </p>
        <p className="text-muted-foreground">
          Включайте, только если у центра есть согласие родителей на обработку переписки в
          мессенджерах. Что именно сохраняется и что не сохраняется никогда — в{" "}
          <a href="/extension/privacy" target="_blank" rel="noreferrer" className="underline">
            политике конфиденциальности расширения
          </a>
          .
        </p>
      </Step>

      {!published && (
        <section className="rounded-lg border p-4 text-sm leading-relaxed space-y-2">
          <h2 className="font-semibold">Как обновлять, пока расширение стоит папкой</h2>
          <p>
            Сами обновления не приходят — пока расширения нет в магазине, это ручная
            операция, и делать её нужно, когда мы пришлём новый архив.
          </p>
          <ol className="list-decimal pl-5 space-y-1">
            <li>Распакуйте новый архив ПОВЕРХ той же папки, заменив файлы.</li>
            <li>
              Откройте <code>chrome://extensions</code> и нажмите круглую стрелку ⟳ на
              карточке «Умной CRM».
            </li>
            <li>Перезагрузите вкладки мессенджеров, которые были открыты.</li>
          </ol>
          <p className="text-muted-foreground">
            Токен вводить заново не нужно — он сохраняется. Обновления нужны прежде всего
            тогда, когда мессенджер меняет вёрстку: панель тогда перестаёт видеть чат.
          </p>
        </section>
      )}

      <section className="rounded-lg border p-4 text-sm leading-relaxed space-y-2">
        <h2 className="font-semibold">Если панель не видит чат</h2>
        <ul className="list-disc pl-5 space-y-1">
          <li>
            <strong>Вкладка была открыта до установки.</strong> Обновите её — панель сама
            предложит кнопку «Обновить вкладку».
          </li>
          <li>
            <strong>Открыт групповой чат.</strong> Панель работает только с личной
            перепиской: за групповым чатом стоит не один человек, и его переписку нельзя
            положить в карточку одного клиента. Во ВКонтакте так же не обслуживаются беседы
            и диалоги с другими сообществами — панель об этом прямо пишет.
          </li>
          <li>
            <strong>Во ВКонтакте открыт список диалогов, а не сам диалог.</strong> Панель
            узнаёт собеседника из адреса страницы, а он появляется только при открытом
            диалоге.
          </li>
          <li>
            <strong>В чате ещё нет сообщений.</strong> В WhatsApp собеседник определяется по
            самим сообщениям — в пустом диалоге определить его неоткуда.
          </li>
          <li>
            <strong>Ничего из перечисленного.</strong> Откройте в панели шестерёнку: внизу
            есть строка диагностики — пришлите её нам, по ней видно, что именно видит
            расширение.
          </li>
        </ul>
      </section>

      <section className="rounded-lg border p-4 text-sm leading-relaxed space-y-2">
        <h2 className="font-semibold">Чтобы клиент находился сам</h2>
        <p>
          Заполняйте в карточке клиента поля мессенджеров — «ВКонтакте», «Телеграм», «MAX».
          Ссылку на страницу можно вставлять целиком, как скопировали:{" "}
          <code>https://vk.ru/annmalafeeva</code> подойдёт.
        </p>
        <p className="text-muted-foreground">
          Если поле не заполнено, панель предложит найти клиента вручную — связь она
          запомнит, и в следующий раз чат опознается сам. В WhatsApp клиент находится по
          номеру телефона из карточки.
        </p>
      </section>
    </div>
  )
}

function Step({ num, title, children }: { num: string; title: string; children: React.ReactNode }) {
  return (
    <section className="rounded-lg border p-4">
      <h2 className="font-semibold mb-2">
        Шаг {num}. {title}
      </h2>
      <div className="text-sm leading-relaxed space-y-2">{children}</div>
    </section>
  )
}
